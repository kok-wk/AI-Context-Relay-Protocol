/* ---------- 主入口 ---------- */

function injectAcrp(projectPath) {
    if (!projectPath) throw new Error('project_path is required');
    const abs = path.resolve(projectPath);
    if (!fs.existsSync(abs)) throw new Error(`Directory not found: ${abs}`);
    if (!fs.statSync(abs).isDirectory()) throw new Error(`Not a directory: ${abs}`);

    const info = detectProject(abs);
    const protocolSummary = loadProtocolSummary();

    fs.writeFileSync(path.join(abs, 'AGENTS.md'), buildAgentsMd(info, protocolSummary));
    fs.writeFileSync(path.join(abs, 'AI-README.md'), buildAiReadmeMd(info));
    const readmeAction = ensureReadme(abs);

    return {
        success: true,
        project_path: abs,
        project_type: info.type,
        files_written: {
            'AGENTS.md': 'generated',
            'AI-README.md': 'generated',
            'README.md': readmeAction,
        },
        detected_files: info.files.length,
        detected_dirs: info.dirs.length,
        next_step: 'Edit the generated files to fill in project-specific content, then git commit. Add GitHub tags ai-context-relay-protocol + ai-docs.',
    };
}

