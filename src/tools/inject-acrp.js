/* ---------- AI-README.md ---------- */

function buildFileMapRows(projectInfo) {
    const rows = [
        `| \`AGENTS.md\` | harness 自动加载 | ACRP 协议摘要 + 指向本文件 | 无需主动读，环境自动注入 |`,
        `| \`AI-README.md\`（本文件） | AI | 项目 AI 入口 | 接到任务先读 |`,
        `| \`README.md\` | 人类 | 项目介绍 | 人类用户 |`,
    ];
    if (projectInfo.type !== 'generic') {
        const cfg = {
            node: 'package.json', rust: 'Cargo.toml', python: 'pyproject.toml',
            go: 'go.mod', java: 'pom.xml',
        }[projectInfo.type];
        rows.push(`| \`${cfg}\` | — | ${projectInfo.type} 构建配置 | 按需 |`);
    }
    for (const d of projectInfo.dirs) rows.push(`| \`${d}/\` | — | 目录 | 按需 |`);
    const skip = ['AGENTS.md', 'AI-README.md', 'README.md', 'package.json', 'Cargo.toml',
        'pyproject.toml', 'requirements.txt', 'go.mod', 'pom.xml'];
    for (const f of projectInfo.files) {
        if (skip.includes(f)) continue;
        rows.push(`| \`${f}\` | — | 文件 | 按需 |`);
    }
    return rows.join('\n');
}

