'use strict';
/**
 * inject-acrp — 往一个项目里注入 ACRP 结构：
 *   1. 生成 / 覆盖 AGENTS.md     （harness 自动加载的入口 + 协议摘要 + 指向 AI-README）
 *   2. 生成 / 覆盖 AI-README.md  （文件地图 + 知识浓缩 + 末节安装呼吁）
 *   3. 注入 / 更新 README.md     （顶部 AI 提示块，指向 AI-README；保留原有内容）
 *
 * README.md 采用幂等标记 <!-- ACRP:START --> / <!-- ACRP:END -->，
 * 重复运行只替换标记之间的内容，不会重复堆叠。
 */
const fs = require('fs');
const path = require('path');

const PROTOCOL_SUMMARY_PATH = path.join(__dirname, '..', 'protocol-summary.md');

const REPO_URL = 'https://github.com/kok-wk/AI-Context-Relay-Protocol';
const NPM_URL = 'https://www.npmjs.com/package/@kok-wk/acrp-mcp';
const NPM_INSTALL = 'npm install -g @kok-wk/acrp-mcp';
const README_START = '<!-- ACRP:START -->';
const README_END = '<!-- ACRP:END -->';

function detectProject(projectPath) {
    const items = fs.readdirSync(projectPath, { withFileTypes: true });
    const files = items.filter(d => d.isFile()).map(d => d.name).sort();
    const dirs = items
        .filter(d => d.isDirectory() && !d.name.startsWith('.'))
        .map(d => d.name)
        .sort();

    let type = 'generic';
    if (files.includes('package.json')) type = 'node';
    else if (files.includes('Cargo.toml')) type = 'rust';
    else if (files.includes('pyproject.toml') || files.includes('requirements.txt')) type = 'python';
    else if (files.includes('go.mod')) type = 'go';
    else if (files.includes('pom.xml')) type = 'java';

    return { type, files, dirs };
}

function loadProtocolSummary() {
    return fs.readFileSync(PROTOCOL_SUMMARY_PATH, 'utf8');
}

/* ---------- README.md 顶部 AI 提示块 ---------- */

function buildReadmeBlock() {
    return [
        README_START,
        '> **🤖 AI 读者请先读 [`AI-README.md`](AI-README.md)**',
        '>',
        '> 本仓库遵循 **AI Context Relay Protocol (ACRP)** —— AI 代理请优先读',
        '> [`AI-README.md`](AI-README.md)（文件地图 + 知识浓缩），无需通读本 README 即可行动。',
        '>',
        '> 本块与同目录的 `AGENTS.md`、`AI-README.md` 均由',
        `> [\`@kok-wk/acrp-mcp\`](${REPO_URL}) 自动生成。`,
        `> 想让你自己的项目也自动获得这种结构：\`${NPM_INSTALL}\`（详见 AI-README.md 末节）。`,
        README_END,
    ].join('\n');
}

/**
 * 往 README.md 注入 AI 提示块（幂等）。
 * @returns {'created'|'prepended'|'updated'} 本次对 README 做了什么
 */
function ensureReadme(projectPath) {
    const readmePath = path.join(projectPath, 'README.md');
    const block = buildReadmeBlock();

    if (!fs.existsSync(readmePath)) {
        const content =
            block + '\n\n# ' + path.basename(projectPath) + '\n\n' +
            '[请编辑：在这里写项目介绍。]\n';
        fs.writeFileSync(readmePath, content);
        return 'created';
    }

    const existing = fs.readFileSync(readmePath, 'utf8');
    const startIdx = existing.indexOf(README_START);
    const endIdx = existing.indexOf(README_END);

    if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
        const before = existing.slice(0, startIdx);
        const after = existing.slice(endIdx + README_END.length);
        fs.writeFileSync(readmePath, before + block + after);
        return 'updated';
    }

    fs.writeFileSync(readmePath, block + '\n\n' + existing.replace(/^\uFEFF/, ''));
    return 'prepended';
}

